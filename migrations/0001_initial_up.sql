-- 0001: начальная схема дашборда координатора IT-инцидентов МТС.
-- Имена ограничений и индексов совпадают с naming convention в app/models/base.py,
-- поэтому `alembic check` не находит расхождений между ORM и БД.
-- Все даты — timestamptz в UTC.

-- ---------------------------------------------------------------------------
-- Журнал снимков: id = revision снимка = eventCursor = SSE id
-- ---------------------------------------------------------------------------
CREATE TABLE dashboard_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    event_type  text        NOT NULL,
    reason      text        NOT NULL,
    payload     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_dashboard_events PRIMARY KEY (id),
    CONSTRAINT ck_dashboard_events_event_type CHECK (event_type IN ('dashboard.changed')),
    CONSTRAINT ck_dashboard_events_reason CHECK (reason IN ('import', 'source', 'expiry'))
);

-- ---------------------------------------------------------------------------
-- Реестр инцидентов: последняя принятая версия каждой записи
-- ---------------------------------------------------------------------------
CREATE TABLE incidents (
    pk                          bigint GENERATED BY DEFAULT AS IDENTITY,
    id                          text        NOT NULL,
    sys_id                      text        NOT NULL,

    header                      text,
    description                 text,
    short_description           text,
    solution                    text,

    product_name                text,
    product_id                  text,
    product_master_id           text,
    product_url                 text,
    service                     text,
    service_id                  text,
    scenario_name               text,
    service_type                text,
    service_type_id             integer,
    inc_type                    text,
    receiving_channel           text,

    state_label                 text,
    state_enum                  text,
    state_id                    integer,
    state_reason                text,
    state_reason_id             text,
    normalized_state            text        NOT NULL,
    status_mismatch             boolean     NOT NULL DEFAULT false,

    priority_id                 smallint    NOT NULL,
    priority                    text,
    urgency_id                  smallint,
    urgency                     text,
    impact_id                   smallint,
    impact                      text,

    assigned_group_name         text,
    assigned_employee           text,
    assigned_employee_login     text,
    initiator_name              text,
    initiator_login             text,

    submit_date                 timestamptz NOT NULL,
    deadline                    timestamptz,
    completion_date             timestamptz,
    last_assignment_to_team_at  timestamptz,
    waiting_exit_date           timestamptz,

    is_effect                   boolean,
    is_reason                   boolean,
    is_double                   boolean,
    is_master                   boolean,
    is_root_incident            boolean,
    is_need_up                  boolean,
    elimination_type            text,
    elimination_type_id         text,

    raw                         jsonb       NOT NULL,
    content_hash                text        NOT NULL,
    incident_revision           integer     NOT NULL DEFAULT 1,

    is_present                  boolean     NOT NULL DEFAULT true,
    removed_at                  timestamptz,

    resolution_phase            text,
    resolved_detected_at        timestamptz,
    recently_resolved_until     timestamptz,

    first_seen_at               timestamptz NOT NULL DEFAULT now(),
    updated_at                  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_incidents PRIMARY KEY (pk),
    CONSTRAINT uq_incidents_id UNIQUE (id),
    CONSTRAINT uq_incidents_sys_id UNIQUE (sys_id),
    CONSTRAINT ck_incidents_priority_id CHECK (priority_id BETWEEN 1 AND 4),
    CONSTRAINT ck_incidents_normalized_state CHECK (
        normalized_state IN ('Assigned', 'WorkInProgress', 'Resolved', 'Closed', 'Research', 'Unknown')
    ),
    CONSTRAINT ck_incidents_resolution_phase CHECK (
        resolution_phase IS NULL OR resolution_phase IN ('research', 'resolved', 'closed')
    ),
    CONSTRAINT ck_incidents_revision_positive CHECK (incident_revision >= 1)
);

CREATE INDEX ix_incidents_is_present ON incidents (is_present);
CREATE INDEX ix_incidents_deadline ON incidents (deadline);
CREATE INDEX ix_incidents_recently_resolved_until ON incidents (recently_resolved_until)
    WHERE recently_resolved_until IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Лента ChangeEvent (API.md §5): одно событие на одну новую ревизию инцидента
-- ---------------------------------------------------------------------------
CREATE TABLE change_events (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    revision           bigint      NOT NULL,
    incident_pk        bigint      NOT NULL,
    incident_revision  integer     NOT NULL,
    sys_id             text        NOT NULL,
    incident_id        text        NOT NULL,
    header             text,
    types              text[]      NOT NULL,
    fields             text[]      NOT NULL DEFAULT '{}',
    previous           jsonb,
    "current"          jsonb,
    at                 timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_change_events PRIMARY KEY (id),
    CONSTRAINT fk_change_events_revision_dashboard_events
        FOREIGN KEY (revision) REFERENCES dashboard_events (id),
    CONSTRAINT fk_change_events_incident_pk_incidents
        FOREIGN KEY (incident_pk) REFERENCES incidents (pk),
    CONSTRAINT uq_change_events_incident_pk UNIQUE (incident_pk, incident_revision),
    CONSTRAINT ck_change_events_types_not_empty CHECK (cardinality(types) > 0)
);

CREATE INDEX ix_change_events_revision ON change_events (revision);
CREATE INDEX ix_change_events_sys_id_id ON change_events (sys_id, id);
CREATE INDEX ix_change_events_types ON change_events USING gin (types);

-- ---------------------------------------------------------------------------
-- Пополевая история изменений
-- ---------------------------------------------------------------------------
CREATE TABLE incident_changes (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    incident_pk        bigint      NOT NULL,
    change_event_id    bigint,
    incident_revision  integer     NOT NULL,
    change_type        text        NOT NULL,
    field              text,
    old_value          jsonb,
    new_value          jsonb,
    observed_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_incident_changes PRIMARY KEY (id),
    CONSTRAINT fk_incident_changes_incident_pk_incidents
        FOREIGN KEY (incident_pk) REFERENCES incidents (pk),
    CONSTRAINT fk_incident_changes_change_event_id_change_events
        FOREIGN KEY (change_event_id) REFERENCES change_events (id),
    CONSTRAINT ck_incident_changes_change_type CHECK (
        change_type IN ('created', 'updated', 'removed', 'restored')
    )
);

CREATE INDEX ix_incident_changes_incident_pk_revision ON incident_changes (incident_pk, incident_revision);
CREATE INDEX ix_incident_changes_change_event_id ON incident_changes (change_event_id);

-- ---------------------------------------------------------------------------
-- Состояние источника (одна строка)
-- ---------------------------------------------------------------------------
CREATE TABLE import_state (
    id                    smallint    NOT NULL DEFAULT 1,
    status                text        NOT NULL DEFAULT 'initializing',
    source_path           text,
    last_checked_at       timestamptz,
    last_success_at       timestamptz,
    last_change_at        timestamptz,
    last_error_at         timestamptz,
    last_error            text,
    error_since           timestamptz,
    consecutive_failures  integer     NOT NULL DEFAULT 0,
    content_hash          text,
    file_mtime_ns         bigint,
    file_size             bigint,
    incident_count        integer,
    warnings              jsonb       NOT NULL DEFAULT '[]'::jsonb,
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_import_state PRIMARY KEY (id),
    CONSTRAINT ck_import_state_single_row CHECK (id = 1),
    CONSTRAINT ck_import_state_status CHECK (status IN ('initializing', 'ok', 'error'))
);

INSERT INTO import_state (id, status) VALUES (1, 'initializing');

-- ---------------------------------------------------------------------------
-- Уведомления координатора и отметки прочтения
-- ---------------------------------------------------------------------------
CREATE TABLE notifications (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    type               text        NOT NULL,
    incident_pk        bigint,
    incident_id        text,
    sys_id             text,
    incident_revision  integer,
    change_event_id    bigint,
    title              text        NOT NULL,
    body               text        NOT NULL DEFAULT '',
    payload            jsonb       NOT NULL DEFAULT '{}'::jsonb,
    dedup_key          text        NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_incident_pk_incidents
        FOREIGN KEY (incident_pk) REFERENCES incidents (pk),
    CONSTRAINT fk_notifications_change_event_id_change_events
        FOREIGN KEY (change_event_id) REFERENCES change_events (id),
    CONSTRAINT uq_notifications_dedup_key UNIQUE (dedup_key),
    CONSTRAINT ck_notifications_type CHECK (
        type IN ('critical.raised', 'coordinator.assigned', 'critical.resolved', 'source.error', 'source.recovered')
    )
);

CREATE INDEX ix_notifications_incident_pk ON notifications (incident_pk);

CREATE TABLE notification_reads (
    notification_id  bigint      NOT NULL,
    user_id          text        NOT NULL,
    read_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_notification_reads PRIMARY KEY (notification_id, user_id),
    CONSTRAINT fk_notification_reads_notification_id_notifications
        FOREIGN KEY (notification_id) REFERENCES notifications (id) ON DELETE CASCADE
);

CREATE INDEX ix_notification_reads_user_id ON notification_reads (user_id);

-- ---------------------------------------------------------------------------
-- ИИ-задачи
-- ---------------------------------------------------------------------------
CREATE TABLE analysis_jobs (
    id                 uuid        NOT NULL DEFAULT gen_random_uuid(),
    incident_pk        bigint      NOT NULL,
    incident_id        text        NOT NULL,
    sys_id             text        NOT NULL,
    kind               text        NOT NULL,
    incident_revision  integer     NOT NULL,
    status             text        NOT NULL DEFAULT 'queued',
    input              jsonb       NOT NULL,
    result             jsonb,
    provider           text,
    model              text        NOT NULL,
    prompt_version     text        NOT NULL,
    attempts           integer     NOT NULL DEFAULT 0,
    max_attempts       integer     NOT NULL DEFAULT 3,
    error              text,
    available_at       timestamptz NOT NULL DEFAULT now(),
    locked_until       timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    started_at         timestamptz,
    finished_at        timestamptz,
    updated_at         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_analysis_jobs PRIMARY KEY (id),
    CONSTRAINT fk_analysis_jobs_incident_pk_incidents
        FOREIGN KEY (incident_pk) REFERENCES incidents (pk),
    -- Одна задача на (инцидент, тип, версия инцидента, модель, версия промпта): защита от дублей.
    CONSTRAINT uq_analysis_jobs_incident_pk UNIQUE (incident_pk, kind, incident_revision, model, prompt_version),
    CONSTRAINT ck_analysis_jobs_kind CHECK (kind IN ('summary')),
    CONSTRAINT ck_analysis_jobs_status CHECK (status IN ('queued', 'running', 'completed', 'failed')),
    CONSTRAINT ck_analysis_jobs_provider CHECK (provider IS NULL OR provider IN ('llm', 'rules')),
    CONSTRAINT ck_analysis_jobs_attempts CHECK (attempts >= 0 AND max_attempts >= 1)
);

CREATE INDEX ix_analysis_jobs_status_available_at ON analysis_jobs (status, available_at);
